//! Conditional nominal schedules attached to generated WAVE selections.
//!
//! ROMFS count mode assumes that the current WAVE index matches the generated
//! record index, the effective Round list retains the three source entries,
//! and no later difficulty update changes the interpolated level settings.
//! Explicit counts can instead represent observed effective queue inputs.
//! Neither mode proves actual spawn success or final enemy positions.

use crate::{
    levels::{QueueCounts, queue_counts},
    records::{GenerationError, WaveSelection},
    schedule::{NominalEntry, ScheduleBranch, ScheduleError, ScheduleInput, nominal_schedule},
    stage_wave::{StageWaveInput, StageWaveOutcome, predict_stage_wave_selections},
};

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum QueueCountSource<'a> {
    /// 11.3.0 ROMFS source rows with `min(current_index, 2)` Round selection.
    RomfsClampedRoundByWave,
    /// Effective `WaveChangeNum` and `RareAppearNum` for each record index.
    Explicit(&'a [QueueCounts; 5]),
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum CountOrigin {
    RomfsClampedRoundByWave,
    Explicit,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub enum NominalScheduleStatus {
    Predicted {
        counts: QueueCounts,
        /// The queue branch is an assumption supplied by the caller.
        assumed_branch: ScheduleBranch,
        entries: Vec<NominalEntry>,
    },
    /// The generated event's ordered Rare queue is not modeled.
    UnsupportedGeneratedEvent(u8),
    /// The supplied counts exceed the modeled queue conditions.
    Rejected(ScheduleError),
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct NominalWavePreview {
    pub selection: WaveSelection,
    pub schedule: NominalScheduleStatus,
}

#[derive(Clone, Debug, PartialEq)]
pub struct NominalPreviewOutcome {
    pub stage_wave: StageWaveOutcome,
    pub count_origin: CountOrigin,
    /// Only record indices generated by the current call are included.
    pub waves: Vec<NominalWavePreview>,
}

/// Attach an event-0/5/6 nominal Rare queue to each generated record when possible.
///
/// `branches` describes the branch reached at schedule-build time for each
/// WAVE, which need not be known when records are first generated. These are
/// generated event/tide values; applying a WAVE can override them later.
pub fn predict_nominal_wave_preview(
    input: StageWaveInput<'_>,
    counts: QueueCountSource<'_>,
    branches: [ScheduleBranch; 5],
) -> Result<NominalPreviewOutcome, GenerationError> {
    let seed = input.seed;
    let stage_wave = predict_stage_wave_selections(input)?;
    let count_origin = match counts {
        QueueCountSource::RomfsClampedRoundByWave => CountOrigin::RomfsClampedRoundByWave,
        QueueCountSource::Explicit(_) => CountOrigin::Explicit,
    };
    let waves = stage_wave
        .generation
        .selections
        .iter()
        .copied()
        .map(|selection| {
            let schedule = if !matches!(selection.event_id, 0 | 5 | 6) {
                NominalScheduleStatus::UnsupportedGeneratedEvent(selection.event_id)
            } else {
                let wave_index = usize::from(selection.wave_index);
                let effective_counts = match counts {
                    QueueCountSource::RomfsClampedRoundByWave => {
                        let round = selection.wave_index.min(2);
                        queue_counts(stage_wave.effective_difficulty, round)
                            .expect("clamped to the source's three rounds")
                    },
                    QueueCountSource::Explicit(values) => values[wave_index],
                };
                match nominal_schedule(ScheduleInput {
                    seed,
                    event_type: selection.event_id,
                    wave_change_num: effective_counts.wave_change_num,
                    rare_appear_num: effective_counts.rare_appear_num,
                    assumed_branch: branches[wave_index],
                }) {
                    Ok(entries) => NominalScheduleStatus::Predicted {
                        counts: effective_counts,
                        assumed_branch: branches[wave_index],
                        entries,
                    },
                    Err(error) => NominalScheduleStatus::Rejected(error),
                }
            };
            NominalWavePreview {
                selection,
                schedule,
            }
        })
        .collect();
    Ok(NominalPreviewOutcome {
        stage_wave,
        count_origin,
        waves,
    })
}

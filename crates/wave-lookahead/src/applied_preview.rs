//! JobType 1 generated records, direct application writes, and nominal queues.
//!
//! Every runtime application state belongs to its original record index. The
//! caller must supply it independently; a preceding predicted WAVE does not
//! establish the next WAVE's actual player count, flags, or previous tide.
//! ROMFS count mode has the same assumptions as [`crate::preview`]. Event 8
//! takes an unresolved indirect handler path; no final applied event is
//! asserted for it.

use crate::{
    applied_wave::{
        ApplyJobOneError, DirectAppliedWave, JobOneApplyState, apply_job_one_direct_writes,
    },
    levels::{QueueCounts, queue_counts},
    preview::{CountOrigin, QueueCountSource},
    records::{GenerationError, WaveSelection},
    schedule::{NominalEntry, ScheduleBranch, ScheduleError, ScheduleInput, nominal_schedule},
    stage_wave::{
        DifficultySource, StageWaveInput, StageWaveOutcome, predict_stage_wave_selections,
    },
};

#[derive(Clone, Debug, Eq, PartialEq)]
pub enum AppliedScheduleStatus {
    Predicted {
        counts: QueueCounts,
        /// The schedule-build branch is a caller-supplied assumption.
        assumed_branch: ScheduleBranch,
        entries: Vec<NominalEntry>,
    },
    /// The applied event has no ordered Rare queue model here.
    UnsupportedAppliedEvent(u8),
    /// Runtime mode class 2/3 skips ordered Rare queue consumption in the
    /// scheduler. Separate event timers may still run.
    QueueBypassedByRuntimeMode,
    /// An indirect handler may change the directly applied state.
    RequiresHandlerObservation(u8),
    /// The supplied counts exceed the modeled queue conditions.
    Rejected(ScheduleError),
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct JobOneSchedulerState {
    /// The scheduler-time `[+0x6690][+0x3c] & !1 == 2` condition. This is
    /// read later than `JobOneApplyState.runtime_mode_forces_mid_tide` and
    /// must be supplied independently because it can change in between.
    pub runtime_mode_bypasses_rare_queue: bool,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct JobOneAppliedWavePreview {
    pub generated: WaveSelection,
    /// Direct writes only; later game-state changes remain unobserved.
    pub direct: DirectAppliedWave,
    pub schedule: AppliedScheduleStatus,
}

#[derive(Clone, Debug, PartialEq)]
pub struct JobOneAppliedPreviewOutcome {
    pub stage_wave: StageWaveOutcome,
    pub count_origin: CountOrigin,
    /// Only record indices generated by this call are included.
    pub waves: Vec<JobOneAppliedWavePreview>,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum AppliedPreviewError {
    RequiresJobTypeOne,
    Generation(GenerationError),
    Apply(ApplyJobOneError),
}

/// Preview JobType 1's direct WAVE application and its nominal Rare queue.
///
/// This consumes one application state per original record index, including
/// after a regeneration cutoff, and one scheduler-time mode state per index.
/// The result does not model event-specific extra timers, species selection,
/// actual spawns, or final enemy positions.
pub fn predict_job_one_applied_preview(
    input: StageWaveInput<'_>,
    counts: QueueCountSource<'_>,
    branches: [ScheduleBranch; 5],
    states: [JobOneApplyState; 5],
    schedulers: [JobOneSchedulerState; 5],
) -> Result<JobOneAppliedPreviewOutcome, AppliedPreviewError> {
    if !matches!(input.difficulty, DifficultySource::JobOne { .. }) {
        return Err(AppliedPreviewError::RequiresJobTypeOne);
    }
    let seed = input.seed;
    let stage_wave =
        predict_stage_wave_selections(input).map_err(AppliedPreviewError::Generation)?;
    let count_origin = match counts {
        QueueCountSource::RomfsClampedRoundByWave => CountOrigin::RomfsClampedRoundByWave,
        QueueCountSource::Explicit(_) => CountOrigin::Explicit,
    };
    let mut waves = Vec::with_capacity(stage_wave.generation.selections.len());
    for generated in stage_wave.generation.selections.iter().copied() {
        let index = usize::from(generated.wave_index);
        let direct = apply_job_one_direct_writes(generated, states[index])
            .map_err(AppliedPreviewError::Apply)?;
        let schedule = if schedulers[index].runtime_mode_bypasses_rare_queue {
            AppliedScheduleStatus::QueueBypassedByRuntimeMode
        } else if direct.requires_handler_observation {
            AppliedScheduleStatus::RequiresHandlerObservation(direct.event_id)
        } else if !matches!(direct.event_id, 0 | 5 | 6) {
            AppliedScheduleStatus::UnsupportedAppliedEvent(direct.event_id)
        } else {
            let effective_counts = match counts {
                QueueCountSource::RomfsClampedRoundByWave => {
                    queue_counts(stage_wave.effective_difficulty, generated.wave_index.min(2))
                        .expect("clamped to the source's three rounds")
                },
                QueueCountSource::Explicit(values) => values[index],
            };
            match nominal_schedule(ScheduleInput {
                seed,
                event_type: direct.event_id,
                wave_change_num: effective_counts.wave_change_num,
                rare_appear_num: effective_counts.rare_appear_num,
                assumed_branch: branches[index],
            }) {
                Ok(entries) => AppliedScheduleStatus::Predicted {
                    counts: effective_counts,
                    assumed_branch: branches[index],
                    entries,
                },
                Err(error) => AppliedScheduleStatus::Rejected(error),
            }
        };
        waves.push(JobOneAppliedWavePreview {
            generated,
            direct,
            schedule,
        });
    }
    Ok(JobOneAppliedPreviewOutcome {
        stage_wave,
        count_origin,
        waves,
    })
}
